#!/usr/bin/env node
/* build-locales.js — regenerates locales.js from the master localization CSV.
 *
 *   node build-locales.js <path to instac/i18n/localizations-all.csv>
 *
 * Languages: the CSV header columns after `i18n=>`, first two letters only.
 * Label: the language's own name (the CSV row keyed by the code, in that
 * language's column), else its English name, else the code.
 */
const fs = require('fs');
const path = require('path');

const file = process.argv[2];
if (!file) { console.error('usage: node build-locales.js <localizations-all.csv>'); process.exit(1); }

function parseCsv (text) {             // RFC 4180: quoted fields, "" escapes, CRLF or LF
  const rows = []; let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false; } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(fs.readFileSync(file, 'utf8').replace(/^﻿/, ''));
const byKey = new Map(rows.map((r) => [r[0], r]));
const en = header.indexOf('en');
const locales = [];
for (const column of header.slice(1)) {
  const code = column.trim().slice(0, 2).toLowerCase();
  if (!/^[a-z]{2}$/.test(code) || locales.some((l) => l.code === code)) continue;
  const row = byKey.get(column) || byKey.get(code);
  const own = row && row[header.indexOf(column)];
  const english = row && en >= 0 ? row[en] : '';
  locales.push({ code, label: (own || english || code).trim() });
}

const out = '/* Generated by build-locales.js from ' + path.basename(file) + ' — do not edit by hand. */\n' +
  'window.VE_LOCALES = ' + JSON.stringify(locales, null, 2) + ';\n';
fs.writeFileSync(path.join(__dirname, 'locales.js'), out);
console.log('locales.js: ' + locales.map((l) => l.code + '=' + l.label).join(', '));
